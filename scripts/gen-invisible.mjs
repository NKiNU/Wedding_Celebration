// Writes backend/internal/domain/zz_generated_tables.go: Go has no Default_Ignorable_Code_Point,
// Cased or Case_Ignorable tables, so they are read off Node's own ICU (the Unicode version the
// TypeScript app runs on). Regenerate with `node scripts/gen-invisible.mjs`.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const tests = {
  invisible: /^[\p{Cc}\p{Cf}\p{Default_Ignorable_Code_Point}]$/u, // normalizeName strips these
  cased: /^\p{Cased}$/u,
  caseIgnorable: /^\p{Case_Ignorable}$/u,
};

function ranges(re) {
  const out = [];
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) continue;
    if (!re.test(String.fromCodePoint(cp))) continue;
    const last = out[out.length - 1];
    if (last && last[1] === cp - 1) last[1] = cp;
    else out.push([cp, cp]);
  }
  return out;
}

const hex = (n) => "0x" + n.toString(16).toUpperCase().padStart(4, "0");
function table(name, rs) {
  const r16 = [], r32 = [];
  for (const [lo, hi] of rs) {
    if (hi <= 0xffff) r16.push([lo, hi]);
    else if (lo > 0xffff) r32.push([lo, hi]);
    else { r16.push([lo, 0xffff]); r32.push([0x10000, hi]); }
  }
  const line = ([lo, hi]) => `\t\t{Lo: ${hex(lo)}, Hi: ${hex(hi)}, Stride: 1},`;
  const latin = r16.filter(([, hi]) => hi <= 0xff).length;
  return `var ${name} = &unicode.RangeTable{
	R16: []unicode.Range16{
${r16.map(line).join("\n")}
	},
	R32: []unicode.Range32{
${r32.map(line).join("\n")}
	},
	LatinOffset: ${latin},
}
`;
}

const body = Object.entries(tests).map(([name, re]) => table(name, ranges(re))).join("\n");
const out = `// Code generated by scripts/gen-invisible.mjs from Node ${process.version} (Unicode ${process.versions.unicode}); DO NOT EDIT.
// Regenerate: node scripts/gen-invisible.mjs

package domain

import "unicode"

${body}`;
const file = fileURLToPath(new URL("../backend/internal/domain/zz_generated_tables.go", import.meta.url));
writeFileSync(file, out);
execFileSync("gofmt", ["-w", file]); // needs the Go toolchain, which the backend needs anyway
